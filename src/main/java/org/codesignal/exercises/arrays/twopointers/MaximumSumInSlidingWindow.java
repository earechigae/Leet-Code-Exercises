package org.codesignal.exercises.arrays.twopointers;

/*
You are given an array of n integers, where n ranges from $1$ to $10^5$, inclusive,
and each number falls within the range of $-10^5$ to $10^5$, inclusive.
Your task is to find the subarray (continuous section) of length k ($1 \le k \le n$) that has the maximum sum using
the two-pointer technique.

The function, maximum_sum, should take an array numbers and an integer k as inputs, and return a pair containing two integers:
the largest sum of a k-length subarray and the index of the first element of this subarray.
If more than one subarray yields the same maximum sum, return the one with the lowest starting index.

The time complexity of your solution should be linear, i.e., O(n), where n is the number of elements in the numbers array.

Expect an input in the following manner:
app.maximumSum(new int[]{2, 1, 5, 1, 3, 2}, 3);

In this example, when k = 3, the subarrays are {2, 1, 5}, {1, 5, 1}, {5, 1, 3}, and {1, 3, 2}.
The maximum sum among these is 9, generated by the subarray {5, 1, 3}.
Therefore, the function's output should be a pair: (9, 2).
The first number represents the maximum sum, and the second number indicates the index of the first element of the maximum subarray.

For the same array, if k = 2,
app.maximumSum(new int[]{2, 1, 5, 1, 3, 2}, 2);

The subarrays are {2, 1}, {1, 5}, {5, 1}, {1, 3}, and {3, 2}.
The maximum sum among these is 6, which is generated by the subarray {1, 5}. The output in this case should be (6, 1).

Hint: For solving this task, you should use the two pointers technique, where both pointers move to the right.
 */

import java.util.ArrayList;
import java.util.List;

public class MaximumSumInSlidingWindow {
    //Do not forget to declare as long variables that are being aggregated
    //In this example maximumSum. Otherwise, it will overflow with big integer values
    public int[] maximumSum(int[] numbers, int k) {
        long maximumSum = Long.MIN_VALUE;
        int minumumPosition = 0;
        long valSum = 0;
        int right = 0;

        for(right = 0; right < k; right++){
            valSum += numbers[right];
        }
        maximumSum = valSum;

        for(int left = 1; left < numbers.length - (k - 1); left++){
            int comingOut = numbers[left - 1];
            valSum -= comingOut;
            int comingIn = numbers[right];
            valSum += comingIn;

            if(valSum > maximumSum){
                minumumPosition = left;
                maximumSum = valSum;
            }
            right += 1;
        }

        return new int[]{(int)maximumSum, minumumPosition};
    }

    public static void main(String[] args) {
        MaximumSumInSlidingWindow msisw = new MaximumSumInSlidingWindow();
        List<int[]> inputArrays = new ArrayList<>();
        List<Integer> kWindowSizes = new ArrayList<>();

        inputArrays.add(new int[]{2, 1, 5, 1, 3, 2});
        kWindowSizes.add(3);

        inputArrays.add(new int[]{2, 1, 5, 1, 3, 2});
        kWindowSizes.add(2);

        inputArrays.add(new int[]{1, 9, -1, -2, 7, 3, -1, 2, 4, -6});
        kWindowSizes.add(5);

        inputArrays.add(new int[]{-2, -3, 4, -1, -2, 1, 5, -3});
        kWindowSizes.add(5);

        inputArrays.add(new int[]{-2, -5, 6, -2, -3, 1, 5, -6});
        kWindowSizes.add(2);

        inputArrays.add(new int[]{1});
        kWindowSizes.add(1);

        inputArrays.add(new int[]{1, -1, 1, -1, 1, -1, 1, -1});
        kWindowSizes.add(2);

        inputArrays.add(new int[]{100, 200, 300, 400});
        kWindowSizes.add(2);

        for (int i = 0; i < inputArrays.size(); i++) {
            int[] array = inputArrays.get(i);
            int k = kWindowSizes.get(i);
            int[] result = msisw.maximumSum(array, k);
            System.out.printf("%d.- For %s, the Maximum sum of %d elements in the array is: Sum: %d, Starting position: %d%n",
                    (i + 1), java.util.Arrays.toString(array), k, result[0], result[1]);
        }


    }
}
